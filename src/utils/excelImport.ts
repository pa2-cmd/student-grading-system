/**
 * =============================================================
 * CAMBRIDGE COURT MARKSHEET EXCEL IMPORT ENGINE
 * =============================================================
 * 
 * Matches EXACT format of Cambridge Court High School marksheets:
 * - Sr. No., Enrollment No., Name, Father Name, Mother Name, DOB, Gender
 * - Subject groups: Theory (80), Oral (20), Total (100)
 * - Single subjects: Draw Th (100), H&PE Th (100), VDMATVS Th (100)
 * - Max Grand Total, Grand Total Obtained, % Marks, Remarks, Grade, Attendance
 * 
 * PRESERVES: Original headers, blank cells, column order
 */

function normalizeHeader(header: string): string {
  return String(header || '').toLowerCase().trim().replace(/\s+/g, ' ').replace(/[.\-_]/g, '').replace(/<br\/?>/gi, ' ');
}

